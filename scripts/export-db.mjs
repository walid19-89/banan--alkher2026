/**
 * Export the live Supabase database into portable PostgreSQL files.
 *
 * Output (all under ./backups, which is gitignored):
 *   schema-portable.sql  full DDL: extensions, types, sequences, tables,
 *                        constraints, indexes, functions, views, triggers,
 *                        RLS + policies, plus a small compatibility shim
 *                        (auth schema/roles) so the dump restores on a plain
 *                        PostgreSQL such as Neon.
 *   data-portable.sql    INSERTs for every public table plus auth.users
 *                        (password hashes travel with the dump so members keep
 *                        their passwords; the file is local-only).
 *   export-report.json   row counts and object counts for verification.
 *
 * The export is read-only: it only runs SELECT/introspection queries through
 * the Supabase CLI (`supabase db query --linked`), which needs no Docker.
 *
 * Usage:
 *   node scripts/export-db.mjs
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const OUT_DIR = path.resolve('backups');

/* ------------------------------------------------------------------ *
 * 1. Introspection: every DDL fragment is produced by PostgreSQL itself
 * ------------------------------------------------------------------ */
const SQL_DDL = String.raw`
select json_build_object(
  'extensions', (
    select coalesce(json_agg('create extension if not exists ' || quote_ident(extname) || ';' order by extname), '[]'::json)
    from pg_extension where extname <> 'plpgsql'
  ),
  'types', (
    select coalesce(json_agg(stmt order by typname), '[]'::json) from (
      select t.typname,
        'create type public.' || quote_ident(t.typname) || ' as enum (' ||
        string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) || ');' as stmt
      from pg_type t
      join pg_enum e on e.enumtypid = t.oid
      join pg_namespace n on n.oid = t.typnamespace
      where n.nspname = 'public'
      group by t.typname
    ) ty
  ),
  'sequences', (
    select coalesce(json_agg('create sequence public.' || quote_ident(sequencename) ||
        ' as ' || data_type ||
        ' increment by ' || increment_by ||
        ' minvalue ' || min_value ||
        ' maxvalue ' || max_value ||
        ' start with ' || coalesce(start_value, min_value) ||
        ' cache ' || cache_size ||
        case when cycle then ' cycle' else ' no cycle' end || ';' order by sequencename), '[]'::json)
    from pg_sequences q
    where schemaname = 'public'
      and not exists (
        select 1
        from pg_class s
        join pg_namespace sn on sn.oid = s.relnamespace
        join pg_depend d on d.objid = s.oid and d.deptype in ('a', 'i')
        where sn.nspname = 'public' and s.relname = q.sequencename
      )
  ),
  'sequences_info', (
    select coalesce(json_agg(json_build_object(
        'qualified', format('public.%I', sequencename),
        'last_value', last_value) order by sequencename), '[]'::json)
    from pg_sequences q
    where schemaname = 'public'
      and not exists (
        select 1
        from pg_class s
        join pg_namespace sn on sn.oid = s.relnamespace
        join pg_depend d on d.objid = s.oid and d.deptype in ('a', 'i')
        where sn.nspname = 'public' and s.relname = q.sequencename
      )
  ),
  'serial_columns', (
    select coalesce(json_agg(json_build_object('table', c.relname, 'column', a.attname)
        order by c.relname, a.attnum), '[]'::json)
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
    where n.nspname = 'public' and not a.attisdropped and a.attnum > 0
      and c.relkind = 'r'
      and (a.attidentity <> '' or pg_get_expr(ad.adbin, ad.adrelid) like 'nextval(%')
  ),
  'tables', (
    select coalesce(json_agg(stmt order by tablename), '[]'::json) from (
      select c.relname as tablename,
        'create table public.' || quote_ident(c.relname) || ' (' ||
        string_agg(
          quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) ||
          case
            when a.attidentity = 'a' then ' generated always as identity'
            when a.attidentity = 'd' then ' generated by default as identity'
            when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
            when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
            else ''
          end ||
          case when a.attnotnull then ' not null' else '' end,
          ', ' order by a.attnum) || ');' as stmt
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
      left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
      where n.nspname = 'public' and c.relkind = 'r'
      group by c.relname
    ) t
  ),
  'functions', (
    select coalesce(json_agg(pg_get_functiondef(p.oid) || ';' order by p.proname, p.oid::regprocedure::text), '[]'::json)
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
  ),
  'constraints', (
    select coalesce(json_agg('alter table public.' || quote_ident(c.relname) ||
        ' add constraint ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid) || ';'
        order by case con.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'f' then 4 else 5 end,
                 c.relname, con.conname), '[]'::json)
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    where con.connamespace = 'public'::regnamespace and con.contype in ('p','u','c','f')
  ),
  'indexes', (
    select coalesce(json_agg(pg_get_indexdef(i.indexrelid) || ';' order by ic.relname), '[]'::json)
    from pg_index i
    join pg_class ic on ic.oid = i.indexrelid
    join pg_namespace n on n.oid = ic.relnamespace
    where n.nspname = 'public'
      and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
  ),
  'views', (
    select coalesce(json_agg('create or replace view public.' || quote_ident(viewname) || ' as ' ||
        pg_get_viewdef(format('public.%I', viewname), true) || ';' order by viewname), '[]'::json)
    from pg_views where schemaname = 'public'
  ),
  'triggers', (
    select coalesce(json_agg(pg_get_triggerdef(t.oid) || ';' order by c.relname, t.tgname), '[]'::json)
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal
  ),
  'rls', (
    select coalesce(json_agg('alter table public.' || quote_ident(c.relname) ||
        ' enable row level security;' order by c.relname), '[]'::json)
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity
  ),
  'policies', (
    select coalesce(json_agg(
        'create policy ' || quote_ident(policyname) || ' on public.' || quote_ident(tablename) ||
        case when permissive = 'RESTRICTIVE' then ' as restrictive' else '' end ||
        ' for ' || lower(cmd) ||
        case when roles::text <> '{public}' then ' to ' || array_to_string(roles, ', ') else '' end ||
        coalesce(' using (' || qual || ')', '') ||
        coalesce(' with check (' || with_check || ')', '') || ';'
        order by tablename, policyname), '[]'::json)
    from pg_policies where schemaname = 'public'
  ),
  'fk_edges', (
    select coalesce(json_agg(json_build_object(
        'table', c.relname,
        'ref', rc.relname)), '[]'::json)
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_class rc on rc.oid = con.confrelid
    where con.contype = 'f' and con.connamespace = 'public'::regnamespace
      and con.confrelid::regclass::text not like 'auth.%'
  ),
  'identity_always', (
    select coalesce(json_agg(distinct c.relname), '[]'::json)
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and a.attidentity = 'a' and not a.attisdropped
  ),
  'generated_columns', (
    select coalesce(json_object_agg(relname, cols), '{}'::json) from (
      select c.relname, json_agg(a.attname order by a.attnum) as cols
      from pg_attribute a
      join pg_class c on c.oid = a.attrelid
      join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and a.attgenerated = 's' and not a.attisdropped
      group by c.relname
    ) g
  ),
  'row_counts', (
    select json_object_agg(table_name, (xpath('/row/c/text()',
        query_to_xml(format('select count(*) as c from public.%I', table_name), false, true, '')))[1]::text::int)
    from information_schema.tables
    where table_schema = 'public' and table_type = 'BASE TABLE'
  )
);
`;

/* ------------------------------------------------------------------ *
 * 2. Data: one JSON payload with every public table
 * ------------------------------------------------------------------ */
const SQL_DATA = String.raw`
create or replace function pg_temp.banan_dump_all() returns jsonb
language plpgsql as $fn$
declare
  rec record;
  part jsonb;
  result jsonb := '{}'::jsonb;
begin
  for rec in
    select tablename from pg_tables where schemaname = 'public' order by tablename
  loop
    execute format('select coalesce(jsonb_agg(t), ''[]''::jsonb) from public.%I t', rec.tablename) into part;
    result := result || jsonb_build_object(rec.tablename, part);
  end loop;
  return result;
end;
$fn$;

select pg_temp.banan_dump_all() as dump;
`;

const SQL_AUTH_USERS = String.raw`
select coalesce(jsonb_agg(u order by u.created_at), '[]'::jsonb) as dump from (
  select id, email, phone, created_at, updated_at, email_confirmed_at,
         last_sign_in_at, encrypted_password, raw_user_meta_data
  from auth.users
) u;
`;

/* ------------------------------------------------------------------ *
 * Helpers
 * ------------------------------------------------------------------ */
function runSql(sqlText) {
  const tmpFile = path.join(
    os.tmpdir(),
    `banan-export-${Date.now()}-${Math.random().toString(16).slice(2)}.sql`
  );
  fs.writeFileSync(tmpFile, sqlText, 'utf8');
  const res = spawnSync(
    'npx',
    ['supabase', 'db', 'query', '--linked', '-f', tmpFile, '--output', 'json'],
    { cwd: process.cwd(), encoding: 'utf8', shell: true, maxBuffer: 512 * 1024 * 1024, timeout: 900_000 }
  );
  fs.unlinkSync(tmpFile);
  const stdout = res.stdout || '';
  const start = stdout.indexOf('{');
  if (start === -1) {
    throw new Error(`no JSON from supabase db query.\nstdout: ${stdout.slice(0, 400)}\nstderr: ${(res.stderr || '').slice(0, 400)}`);
  }
  const parsed = JSON.parse(stdout.slice(start));
  if (!parsed.rows || !parsed.rows.length) throw new Error('empty result set');
  return Object.values(parsed.rows[0])[0];
}

function quoteStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (typeof value === 'object') return quoteStr(JSON.stringify(value));
  return quoteStr(value);
}

/** Dependency order for INSERTs so foreign keys are always satisfied. */
function orderTables(tables, edges) {
  const deps = new Map(tables.map((t) => [t, new Set()]));
  for (const e of edges) {
    if (deps.has(e.table) && deps.has(e.ref) && e.table !== e.ref) deps.get(e.table).add(e.ref);
  }
  const ordered = [];
  const done = new Set();
  let guard = 0;
  while (ordered.length < tables.length && guard < tables.length * tables.length + 10) {
    guard += 1;
    for (const t of tables) {
      if (done.has(t)) continue;
      if ([...deps.get(t)].every((d) => done.has(d))) {
        ordered.push(t);
        done.add(t);
      }
    }
  }
  for (const t of tables) if (!done.has(t)) ordered.push(t);
  return ordered;
}

/* ------------------------------------------------------------------ *
 * 3. Build the files
 * ------------------------------------------------------------------ */
function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const stamp = new Date().toISOString();

  console.log('· reading schema from the live database ...');
  const ddl = runSql(SQL_DDL);

  // Supabase-only extensions that do not exist on a plain PostgreSQL host.
  // Nothing in the schema or the API uses them (pg_cron was used for the old
  // in-database scheduler, but backups/dues run through GitHub Actions now).
  const SKIP_EXTENSIONS = ['pg_cron', 'pg_net', 'pg_graphql', 'pgsodium', 'supabase_vault', 'vault', 'pg_stat_statements'];
  const skippedExtensions = (ddl.extensions || []).filter((stmt) =>
    SKIP_EXTENSIONS.some((name) => stmt.includes(`"${name}"`) || stmt.includes(` ${name};`))
  );
  ddl.extensions = (ddl.extensions || []).filter((stmt) => !skippedExtensions.includes(stmt));

  console.log('· reading table data ...');
  const data = runSql(SQL_DATA);

  console.log('· reading auth users ...');
  const authUsers = runSql(SQL_AUTH_USERS);

  const preamble = String.raw`-- =====================================================================
-- Banan Charity Fund - portable PostgreSQL schema
-- Generated ${stamp}
--
-- Restores on any PostgreSQL 15+ (Neon, Railway, self-hosted, ...).
-- It is NOT a Supabase project backup: auth.users is a plain table here,
-- and auth.uid()/auth.role()/auth.jwt() are compatibility stubs that read
-- request.jwt.claims, exactly like Supabase does inside PostgREST.
-- =====================================================================

begin;

-- Compatibility shim so the dump restores outside Supabase.
create schema if not exists auth;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon nologin noinherit;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin noinherit;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then
    create role service_role nologin noinherit bypassrls;
  end if;
end
$$;

create table if not exists auth.users (
  id uuid primary key,
  email text,
  phone text,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  email_confirmed_at timestamptz,
  last_sign_in_at timestamptz,
  encrypted_password text,
  raw_user_meta_data jsonb default '{}'::jsonb
);

create or replace function auth.uid() returns uuid
language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

create or replace function auth.role() returns text
language sql stable as $$
  select nullif(current_setting('request.jwt.claim.role', true), '')
$$;

create or replace function auth.jwt() returns jsonb
language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb)
$$;

-- Bodies are validated lazily, exactly like pg_dump does, so the order of
-- functions and views does not matter.
set check_function_bodies = false;
`;

  const sections = [
    ['-- extensions', ddl.extensions],
    ['-- enum types', ddl.types],
    ['-- sequences', ddl.sequences],
    ['-- tables', ddl.tables],
    ['-- functions', ddl.functions],
    ['-- constraints', ddl.constraints],
    ['-- indexes', ddl.indexes],
    ['-- views', ddl.views],
    ['-- triggers', ddl.triggers],
    ['-- row level security', ddl.rls],
    ['-- policies', ddl.policies],
  ];

  let schema = preamble;
  for (const [title, list] of sections) {
    if (!list || !list.length) continue;
    schema += `\n${title}\n` + list.join('\n') + '\n';
  }
  schema += '\ncommit;\n';

  const generated = new Set(Object.values(ddl.generated_columns || {}).flat());
  const identityAlways = new Set(ddl.identity_always || []);
  const publicTables = Object.keys(data).sort();
  const ordered = orderTables(publicTables, ddl.fk_edges || []);

  const parts = [
    `-- =====================================================================`,
    `-- Banan Charity Fund - portable data`,
    `-- Generated ${stamp}`,
    `-- Contains personal data and password hashes. Keep this file private.`,
    `-- =====================================================================`,
    ``,
    `begin;`,
    `set check_function_bodies = false;`,
    ``,
    `-- The import must reproduce the exact rows, so user triggers stay off until`,
    `-- the end (they would otherwise write extra audit/event rows while loading).`,
    `do $$`,
    `declare r record;`,
    `begin`,
    `  for r in select tablename from pg_tables where schemaname = 'public' loop`,
    `    execute format('alter table public.%I disable trigger user', r.tablename);`,
    `  end loop;`,
    `end`,
    `$$;`,
    ``,
    `-- auth users (bcrypt hashes preserved so members keep their passwords)`,
  ];

  if (authUsers.length) {
    const cols = Object.keys(authUsers[0]);
    const colList = cols.map((c) => `"${c}"`).join(', ');
    for (const row of authUsers) {
      parts.push(
        `insert into auth.users (${colList}) values (${cols.map((c) => sqlLiteral(row[c])).join(', ')}) on conflict (id) do nothing;`
      );
    }
  } else {
    parts.push('-- (no auth users)');
  }

  for (const table of ordered) {
    const rows = data[table] || [];
    parts.push('', `-- ${table}: ${rows.length} row(s)`);
    if (!rows.length) continue;
    const columns = Object.keys(rows[0]).filter((c) => !generated.has(c));
    for (const row of rows) {
      const override = identityAlways.has(table) ? ' overriding system value' : '';
      parts.push(
        `insert into public."${table}" (${columns.map((c) => `"${c}"`).join(', ')})${override} values (${columns
          .map((c) => sqlLiteral(row[c]))
          .join(', ')});`
      );
    }
  }

  parts.push('', '-- keep identity/serial columns ahead of the imported rows');
  for (const seq of ddl.sequences_info || []) {
    if (seq.last_value !== null && seq.last_value !== undefined) {
      parts.push(`select setval('${seq.qualified}', ${seq.last_value}, true);`);
    }
  }
  for (const col of ddl.serial_columns || []) {
    const table = `public.${col.table}`;
    parts.push(
      `select setval(pg_get_serial_sequence('${table}', '${col.column}'), ` +
        `coalesce((select max("${col.column}") from ${table}), 1), ` +
        `(select max("${col.column}") from ${table}) is not null);`
    );
  }
  parts.push(
    '',
    '-- turn the application triggers back on',
    'do $$',
    'declare r record;',
    'begin',
    `  for r in select tablename from pg_tables where schemaname = 'public' loop`,
    `    execute format('alter table public.%I enable trigger user', r.tablename);`,
    '  end loop;',
    'end',
    '$$;',
    '',
    'commit;',
    ''
  );

  fs.writeFileSync(path.join(OUT_DIR, 'schema-portable.sql'), schema, 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, 'data-portable.sql'), parts.join('\n'), 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, 'auth-users.json'), JSON.stringify(authUsers, null, 2), 'utf8');

  const report = {
    generated_at: stamp,
    database: {
      tables: ddl.tables.length,
      functions: ddl.functions.length,
      triggers: ddl.triggers.length,
      policies: ddl.policies.length,
      indexes_including_constraint_backed: ddl.indexes.length,
      enums: ddl.types.length,
      sequences: ddl.sequences.length,
    },
    rows: Object.fromEntries(publicTables.map((t) => [t, (data[t] || []).length])),
    auth_users: authUsers.length,
    skipped_extensions: skippedExtensions,
    totals: {
      public_rows: publicTables.reduce((sum, t) => sum + (data[t] || []).length, 0),
    },
    files: {
      schema_bytes: Buffer.byteLength(schema, 'utf8'),
      data_bytes: Buffer.byteLength(parts.join('\n'), 'utf8'),
    },
  };
  fs.writeFileSync(path.join(OUT_DIR, 'export-report.json'), JSON.stringify(report, null, 2), 'utf8');

  console.log(JSON.stringify(report, null, 2));
}

main();
